//! `veneer init`: scaffold `.veneer/veneer.yaml` from files the project already has.

use std::path::{Path, PathBuf};
use std::process::ExitCode;

#[derive(Debug, clap::Args)]
pub struct InitArgs {
    /// Project directory (default: current directory).
    pub dir: Option<PathBuf>,
    /// Overwrite an existing .veneer/veneer.yaml.
    #[arg(long)]
    pub force: bool,
    /// Base image for `veneer bake`.
    #[arg(long, default_value = "ubuntu:24.04")]
    pub base: String,
}

const TOOL_FILES: &[&str] = &[
    "mise.toml",
    ".mise.toml",
    ".tool-versions",
    ".nvmrc",
    ".node-version",
    ".python-version",
];
const COMPOSE_FILES: &[&str] = &[
    "compose.yaml",
    "compose.yml",
    "docker-compose.yaml",
    "docker-compose.yml",
];
const DEP_FILES: &[&str] = &[
    "package.json",
    "pyproject.toml",
    "requirements.txt",
    "Cargo.toml",
    "go.mod",
    "Gemfile",
];
const PACKAGE_FILES: &[&str] = &["Brewfile", "apt.txt"];

fn first(root: &Path, names: &[&str]) -> Option<String> {
    names
        .iter()
        .find(|n| root.join(n).is_file())
        .map(|n| n.to_string())
}

/// The generated spec text and the list of detected files.
pub fn scaffold(root: &Path, base: &str) -> (String, Vec<String>) {
    let mut found = Vec::new();
    let mut y = String::from("# yaml-language-server: $schema=./veneer.schema.json\n");
    y.push_str(
        "# Generated by `veneer init`. See `veneer check --resolved` for the merged result.\n",
    );
    y.push_str(&format!("version: 1\nbase: {base}\n"));
    if let Some(f) = first(root, PACKAGE_FILES) {
        y.push_str(&format!("packages:\n  - from: ../{f}\n"));
        found.push(f);
    }
    if let Some(f) = first(root, TOOL_FILES) {
        y.push_str(&format!("tools:\n  from: ../{f}\n"));
        found.push(f);
    }
    let deps: Vec<&&str> = DEP_FILES
        .iter()
        .filter(|n| root.join(n).is_file())
        .collect();
    if !deps.is_empty() {
        y.push_str("deps:\n");
        for d in deps {
            y.push_str(&format!("  - from: ../{d}\n"));
            found.push(d.to_string());
        }
    }
    if let Some(f) = first(root, COMPOSE_FILES) {
        y.push_str(&format!("services:\n  from: ../{f}\n"));
        found.push(f);
    }
    y.push_str("env:\n  VENEER_WORKSPACE: \"{{ workspace.id }}\"\n");
    (y, found)
}

pub fn run(args: InitArgs) -> ExitCode {
    let root = args.dir.clone().unwrap_or_else(|| PathBuf::from("."));
    let spec = root.join(".veneer/veneer.yaml");
    if spec.exists() && !args.force {
        eprintln!(
            "error: {} already exists (use --force to overwrite)",
            spec.display()
        );
        return ExitCode::from(2);
    }
    let (text, found) = scaffold(&root, &args.base);
    let write = std::fs::create_dir_all(root.join(".veneer"))
        .and_then(|_| std::fs::write(&spec, &text))
        .and_then(|_| {
            std::fs::write(
                root.join(".veneer/veneer.schema.json"),
                veneer_spec::json_schema_string(),
            )
        });
    if let Err(e) = write {
        eprintln!("error: cannot write {}: {e}", spec.display());
        return ExitCode::from(1);
    }
    if found.is_empty() {
        eprintln!(
            "✓ wrote {} (no existing tool, dependency, or compose files detected)",
            spec.display()
        );
    } else {
        eprintln!("✓ wrote {} using {}", spec.display(), found.join(", "));
    }
    eprintln!("next: veneer check --resolved");
    ExitCode::SUCCESS
}
