//! `veneer bake --target cloud-init` (standards proposal §5.2).
//!
//! Emits a `#cloud-config` user-data document that stages the workspace on the first boot
//! of a **stock** cloud image: install a pinned veneer, deliver the project, run
//! `veneer apply`, then announce readiness (console marker + `/run/veneer/ready`).
//! `--seed` also packs a NoCloud seed ISO (volume label `cidata`) for local hypervisors.

use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::Command;

use veneer_exec::{ExecError, Log, Result, run_logged};

use crate::{READY_MARKER, STATE_DIR};

/// Smallest common user-data limit (EC2).
pub const USER_DATA_LIMIT: usize = 16 * 1024;
pub const READY_FILE: &str = "/run/veneer/ready";
const BOOT_SCRIPT: &str = "/opt/veneer/boot.sh";
const PROJECT_TAR: &str = "/opt/veneer/project.tar.gz";
const EMBEDDED_BIN: &str = "/opt/veneer/bin/veneer";

/// How the instance gets the veneer binary.
#[derive(Debug, Clone)]
pub enum Install {
    /// Embedded in user-data (gzip + base64). Fine for NoCloud; too large for most clouds.
    Embed(PathBuf),
    /// Downloaded from a release base URL, verified against inlined sha256 sums.
    Release {
        base_url: String,
        /// (`aarch64` | `x86_64`, sha256 of `veneer-<arch>-unknown-linux-musl.tar.xz`)
        sums: Vec<(String, String)>,
    },
}

/// Where the project comes from.
#[derive(Debug, Clone)]
pub enum Project {
    /// The local project directory, embedded as a tarball. `entry` is relative to it.
    Embed { root: PathBuf, entry: String },
    /// A remote source veneer can fetch itself (`github:`, `git+…`, `https:`, `oci://`).
    Remote(String),
}

#[derive(Debug, Clone)]
pub struct CloudInit {
    pub install: Install,
    pub project: Project,
    pub workspace_id: String,
    /// Only run the workspace phase (the image was baked with `--target disk`).
    pub prebaked: bool,
    /// Extra `apply` arguments (`--overlay`, `--set`), already rewritten for the instance.
    pub extra_args: Vec<String>,
}

const SKIP_DIRS: &[&str] = &[".git", "target", "node_modules", ".venv", ".veneer-state"];

/// Standard base64 (RFC 4648) with padding.
pub fn base64(bytes: &[u8]) -> String {
    const T: &[u8; 64] = b"ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    let mut out = String::with_capacity(bytes.len().div_ceil(3) * 4);
    for chunk in bytes.chunks(3) {
        let b = [
            chunk[0],
            *chunk.get(1).unwrap_or(&0),
            *chunk.get(2).unwrap_or(&0),
        ];
        let n = (b[0] as u32) << 16 | (b[1] as u32) << 8 | b[2] as u32;
        out.push(T[(n >> 18) as usize & 63] as char);
        out.push(T[(n >> 12) as usize & 63] as char);
        out.push(if chunk.len() > 1 {
            T[(n >> 6) as usize & 63] as char
        } else {
            '='
        });
        out.push(if chunk.len() > 2 {
            T[n as usize & 63] as char
        } else {
            '='
        });
    }
    out
}

fn gzip(bytes: &[u8]) -> Result<Vec<u8>> {
    let mut enc = flate2::write::GzEncoder::new(Vec::new(), flate2::Compression::best());
    enc.write_all(bytes)
        .and_then(|_| enc.finish())
        .map_err(|e| ExecError::failed(format!("gzip failed: {e}")))
}

fn add_tree(b: &mut tar::Builder<Vec<u8>>, root: &Path, dir: &Path) -> std::io::Result<()> {
    let mut entries: Vec<_> = std::fs::read_dir(dir)?.flatten().collect();
    entries.sort_by_key(|e| e.file_name());
    for entry in entries {
        let name = entry.file_name();
        if SKIP_DIRS.iter().any(|s| name == *s) {
            continue;
        }
        let path = entry.path();
        let rel = path.strip_prefix(root).unwrap_or(&path);
        let ty = entry.file_type()?;
        if ty.is_dir() {
            b.append_dir(rel, &path)?;
            add_tree(b, root, &path)?;
        } else if ty.is_file() || ty.is_symlink() {
            b.append_path_with_name(&path, rel)?;
        }
    }
    Ok(())
}

/// The project directory as a gzipped tarball (VCS and build output excluded).
pub fn project_tarball(root: &Path) -> Result<Vec<u8>> {
    let mut b = tar::Builder::new(Vec::new());
    b.follow_symlinks(false);
    add_tree(&mut b, root, root)
        .map_err(|e| ExecError::failed(format!("cannot pack {}: {e}", root.display())))?;
    let tar = b
        .into_inner()
        .map_err(|e| ExecError::failed(format!("cannot pack project: {e}")))?;
    gzip(&tar)
}

fn sh_quote(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

/// The first-boot script.
pub fn boot_script(ci: &CloudInit) -> String {
    let mut s = String::from(
        "#!/bin/sh\n# Generated by `veneer bake --target cloud-init`.\nset -eu\n\
         log=/var/log/veneer-boot.log\nexec >>\"$log\" 2>&1\n\
         say() { echo \"$*\"; echo \"$*\" >/dev/console 2>/dev/null || true; }\n\
         fail() { say \"veneer: workspace failed ($*); see $log\"; exit 1; }\n",
    );
    s.push_str("if ! command -v veneer >/dev/null 2>&1; then\n");
    match &ci.install {
        Install::Embed(_) => {
            s.push_str(&format!(
                "  install -m 0755 {EMBEDDED_BIN} /usr/local/bin/veneer || fail install\n"
            ));
        }
        Install::Release { base_url, sums } => {
            s.push_str("  case \"$(uname -m)\" in\n");
            for (arch, sum) in sums {
                let pat = match arch.as_str() {
                    "aarch64" => "aarch64|arm64",
                    _ => "x86_64|amd64",
                };
                s.push_str(&format!(
                    "    {pat}) t={arch}-unknown-linux-musl; sum={sum} ;;\n"
                ));
            }
            s.push_str("    *) fail \"unsupported architecture $(uname -m)\" ;;\n  esac\n");
            s.push_str(&format!(
                "  tmp=$(mktemp -d)\n  url={}/veneer-$t.tar.xz\n\
                 \x20 for i in 1 2 3 4 5; do curl -fsSL \"$url\" -o \"$tmp/v.tar.xz\" && break || sleep $((i * 2)); done\n\
                 \x20 echo \"$sum  $tmp/v.tar.xz\" | sha256sum -c - || fail \"checksum mismatch for $url\"\n\
                 \x20 tar -xJf \"$tmp/v.tar.xz\" -C \"$tmp\" || fail extract\n\
                 \x20 install -m 0755 \"$tmp/veneer-$t/veneer\" /usr/local/bin/veneer\n",
                sh_quote(base_url.trim_end_matches('/'))
            ));
        }
    }
    s.push_str("fi\n");
    let spec = match &ci.project {
        Project::Embed { entry, .. } => {
            s.push_str(&format!(
                "mkdir -p {dir}\ntar -xzf {PROJECT_TAR} -C {dir} || fail \"unpack project\"\n",
                dir = crate::PROJECT_DIR
            ));
            format!("{}/{entry}", crate::PROJECT_DIR)
        }
        Project::Remote(src) => src.clone(),
    };
    let mut args = vec![
        "apply".to_string(),
        sh_quote(&spec),
        "--id".into(),
        sh_quote(&ci.workspace_id),
        "--json".into(),
    ];
    if ci.prebaked {
        args.push("--phase".into());
        args.push("workspace".into());
    }
    args.extend(ci.extra_args.iter().map(|a| sh_quote(a)));
    s.push_str(&format!(
        "export HOME=${{HOME:-/root}} VENEER_STATE_DIR={STATE_DIR} VENEER_READY_FILE={READY_FILE}\n\
         export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin\n\
         veneer {} >/var/log/veneer-apply.ndjson 2>>\"$log\" || fail apply\n\
         say \"{READY_MARKER}\"\n",
        args.join(" ")
    ));
    s
}

/// YAML double-quoted scalar (JSON string syntax is valid YAML).
fn y(s: &str) -> String {
    serde_json::to_string(s).expect("strings serialize")
}

/// The `#cloud-config` document.
pub fn user_data(ci: &CloudInit) -> Result<String> {
    let mut files: Vec<(String, String, &str, &str)> = Vec::new();
    files.push((
        BOOT_SCRIPT.into(),
        base64(&gzip(boot_script(ci).as_bytes())?),
        "gz+b64",
        "0755",
    ));
    if let Project::Embed { root, .. } = &ci.project {
        files.push((
            PROJECT_TAR.into(),
            base64(&project_tarball(root)?),
            "b64",
            "0600",
        ));
    }
    if let Install::Embed(bin) = &ci.install {
        let bytes = std::fs::read(bin).map_err(|e| {
            ExecError::failed(format!("cannot read veneer binary {}: {e}", bin.display()))
        })?;
        files.push((
            EMBEDDED_BIN.into(),
            base64(&gzip(&bytes)?),
            "gz+b64",
            "0755",
        ));
    }
    let mut out =
        String::from("#cloud-config\n# Generated by `veneer bake --target cloud-init`.\n");
    out.push_str("write_files:\n");
    for (path, content, encoding, perms) in &files {
        out.push_str(&format!(
            "  - path: {}\n    owner: \"root:root\"\n    permissions: {}\n    encoding: {}\n    content: {}\n",
            y(path),
            y(perms),
            y(encoding),
            y(content)
        ));
    }
    out.push_str(&format!("runcmd:\n  - [\"sh\", {}]\n", y(BOOT_SCRIPT)));
    Ok(out)
}

/// NoCloud `meta-data` (the instance id changes with the user-data, so a re-seeded VM reruns).
pub fn meta_data(user_data: &str) -> String {
    let id = &blake3::hash(user_data.as_bytes()).to_hex()[..16];
    format!("instance-id: veneer-{id}\nlocal-hostname: veneer\n")
}

fn have(program: &str) -> bool {
    std::env::var_os("PATH")
        .is_some_and(|p| std::env::split_paths(&p).any(|d| d.join(program).is_file()))
}

/// Writes a NoCloud seed ISO (volume label `cidata`) holding `user-data` and `meta-data`.
pub fn seed_iso(user_data: &str, out: &Path, log: &mut Log) -> Result<()> {
    let dir = tempfile::tempdir().map_err(|e| ExecError::failed(e.to_string()))?;
    std::fs::write(dir.path().join("user-data"), user_data)
        .and_then(|_| std::fs::write(dir.path().join("meta-data"), meta_data(user_data)))
        .map_err(|e| ExecError::failed(e.to_string()))?;
    let out_abs = if out.is_absolute() {
        out.to_path_buf()
    } else {
        std::env::current_dir()
            .map_err(|e| ExecError::failed(e.to_string()))?
            .join(out)
    };
    let files = ["user-data", "meta-data"];
    for tool in ["xorriso", "genisoimage", "mkisofs"] {
        if have(tool) {
            let mut c = Command::new(tool);
            if tool == "xorriso" {
                c.args(["-as", "mkisofs"]);
            }
            c.current_dir(dir.path())
                .args(["-quiet", "-volid", "cidata", "-joliet", "-rock", "-o"])
                .arg(&out_abs)
                .args(files);
            return run_logged(&mut c, log);
        }
    }
    if have("hdiutil") {
        let _ = std::fs::remove_file(&out_abs);
        return run_logged(
            Command::new("hdiutil")
                .args([
                    "makehybrid",
                    "-iso",
                    "-joliet",
                    "-default-volume-name",
                    "cidata",
                    "-o",
                ])
                .arg(&out_abs)
                .arg(dir.path()),
            log,
        );
    }
    // Fall back to xorriso in a container.
    let parent = out_abs.parent().unwrap_or(Path::new("/"));
    let name = out_abs
        .file_name()
        .map(|n| n.to_string_lossy().into_owned())
        .unwrap_or_else(|| "seed.iso".into());
    run_logged(
        Command::new("docker")
            .args(["run", "--rm", "-v"])
            .arg(format!("{}:/in:ro", dir.path().display()))
            .arg("-v")
            .arg(format!("{}:/out", parent.display()))
            .args([
                "alpine:3.20",
                "sh",
                "-c",
                &format!(
                    "apk add --no-cache xorriso >/dev/null && cd /in && xorriso -as mkisofs -quiet -volid cidata -joliet -rock -o /out/{name} user-data meta-data"
                ),
            ]),
        log,
    )
}

/// sha256 sums for both Linux release archives, read from `<base>/<asset>.sha256`.
pub fn release_sums(base_url: &str) -> Result<Vec<(String, String)>> {
    let mut sums = Vec::new();
    for arch in ["x86_64", "aarch64"] {
        let url = format!(
            "{}/veneer-{arch}-unknown-linux-musl.tar.xz.sha256",
            base_url.trim_end_matches('/')
        );
        let text = ureq::get(&url)
            .call()
            .map_err(|e| ExecError::failed(format!("GET {url}: {e}")))?
            .body_mut()
            .read_to_string()
            .map_err(|e| ExecError::failed(format!("GET {url}: {e}")))?;
        let sum = text
            .split_whitespace()
            .next()
            .filter(|s| s.len() == 64 && s.chars().all(|c| c.is_ascii_hexdigit()))
            .ok_or_else(|| ExecError::failed(format!("{url} does not hold a sha256 sum")))?;
        sums.push((arch.to_string(), sum.to_string()));
    }
    Ok(sums)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn base64_matches_rfc4648_vectors() {
        for (i, o) in [
            ("", ""),
            ("f", "Zg=="),
            ("fo", "Zm8="),
            ("foo", "Zm9v"),
            ("foob", "Zm9vYg=="),
            ("fooba", "Zm9vYmE="),
            ("foobar", "Zm9vYmFy"),
        ] {
            assert_eq!(base64(i.as_bytes()), o);
        }
    }

    #[test]
    fn boot_script_installs_verifies_and_applies() {
        let ci = CloudInit {
            install: Install::Release {
                base_url: "https://example.com/r/".into(),
                sums: vec![
                    ("x86_64".into(), "a".repeat(64)),
                    ("aarch64".into(), "b".repeat(64)),
                ],
            },
            project: Project::Remote("github:acme/env".into()),
            workspace_id: "agent".into(),
            prebaked: true,
            extra_args: vec!["--set".into(), "x=1".into()],
        };
        let s = boot_script(&ci);
        assert!(s.contains("x86_64|amd64) t=x86_64-unknown-linux-musl; sum=aaaa"));
        assert!(s.contains("url='https://example.com/r'/veneer-$t.tar.xz"));
        assert!(s.contains("sha256sum -c -"));
        assert!(s.contains(
            "veneer apply 'github:acme/env' --id 'agent' --json --phase workspace '--set' 'x=1'"
        ));
        assert!(s.contains(READY_MARKER));
        let ud = user_data(&ci).unwrap();
        assert!(ud.starts_with("#cloud-config\n"));
        assert!(ud.contains("encoding: \"gz+b64\""));
        assert!(ud.contains("runcmd:\n  - [\"sh\", \"/opt/veneer/boot.sh\"]"));
    }
}
