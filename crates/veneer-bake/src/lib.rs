fn qemu_img(ctx: &Path, script: &str, log: &mut Log) -> Result<()> {
    run_logged(
        Command::new("docker")
            .args(["run", "--rm", "-v"])
            .arg(format!("{}:/w", ctx.display()))
            .args([
                "alpine:3.20",
                "sh",
                "-c",
                &format!("set -e; apk add --no-cache qemu-img >/dev/null; {script}"),
            ]),
        log,
    )
}

/// A fixed VHD whose virtual size is a whole number of MiB (Azure and Hyper-V require it).
fn fixed_vhd(ctx: &Path, raw: &Path, out: &Path, log: &mut Log) -> Result<()> {
    let name = raw.file_name().unwrap().to_string_lossy().to_string();
    qemu_img(
        ctx,
        &format!(
            "cd /w; size=$(stat -c %s {name}); mib=$(( (size + 1048575) / 1048576 )); \
             qemu-img resize -f raw {name} $((mib * 1048576)) >/dev/null; \
             qemu-img convert -f raw -O vpc -o subformat=fixed,force_size {name} disk.vhd"
        ),
        log,
    )?;
    std::fs::rename(ctx.join("disk.vhd"), out)
        .or_else(|_| std::fs::copy(ctx.join("disk.vhd"), out).map(|_| ()))
        .map_err(|e| ExecError::failed(format!("cannot place {}: {e}", out.display())))
}

