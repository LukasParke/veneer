fn xml_escape(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
        .replace('"', "&quot;")
}

fn sha256_file(p: &Path) -> Result<String> {
    use sha2::Digest;
    let mut f = std::fs::File::open(p).map_err(|e| ExecError::failed(e.to_string()))?;
    let mut h = sha2::Sha256::new();
    std::io::copy(&mut f, &mut h).map_err(|e| ExecError::failed(e.to_string()))?;
    Ok(hex::encode(h.finalize()))
}

/// An OVA: tar of `<name>.ovf` (first, as the spec requires), the VMDK, and a SHA-256 manifest.
fn ova(ctx: &Path, raw: &Path, out: &Path, opts: &BakeOptions, log: &mut Log) -> Result<()> {
    let name = out
        .file_stem()
        .map(|s| s.to_string_lossy().to_string())
        .unwrap_or_else(|| "veneer".into());
    let vmdk = format!("{name}-disk1.vmdk");
    let raw_name = raw.file_name().unwrap().to_string_lossy().to_string();
    qemu_img(
        ctx,
        &format!(
            "cd /w; qemu-img convert -f raw -O vmdk -o subformat=streamOptimized,adapter_type=lsilogic {raw_name} {vmdk}"
        ),
        log,
    )?;
    let vmdk_path = ctx.join(&vmdk);
    let vmdk_size = std::fs::metadata(&vmdk_path)
        .map_err(|e| ExecError::failed(e.to_string()))?
        .len();
    let capacity = std::fs::metadata(raw)
        .map_err(|e| ExecError::failed(e.to_string()))?
        .len();
    let _ = opts;
    let ovf_name = format!("{name}.ovf");
    let ovf_text = ovf(&name, &vmdk, vmdk_size, capacity, 2, 2048);
    std::fs::write(ctx.join(&ovf_name), &ovf_text).map_err(|e| ExecError::failed(e.to_string()))?;
    let mf_name = format!("{name}.mf");
    let mf = format!(
        "SHA256({ovf_name})= {}\nSHA256({vmdk})= {}\n",
        sha256_file(&ctx.join(&ovf_name))?,
        sha256_file(&vmdk_path)?
    );
    std::fs::write(ctx.join(&mf_name), mf).map_err(|e| ExecError::failed(e.to_string()))?;
    let file = std::fs::File::create(out)
        .map_err(|e| ExecError::failed(format!("cannot create {}: {e}", out.display())))?;
    let mut b = tar::Builder::new(file);
    b.mode(tar::HeaderMode::Deterministic);
    for f in [&ovf_name, &vmdk, &mf_name] {
        b.append_path_with_name(ctx.join(f), f)
            .map_err(|e| ExecError::failed(e.to_string()))?;
    }
    b.finish().map_err(|e| ExecError::failed(e.to_string()))
}
