//! veneer-bake: runs the build phase into a snapshot (design spec §7).
//!
//! `oci`: a generated Containerfile with one `RUN veneer apply --phase build --only <group>`
//! per layer, so BuildKit caches each group independently. Each layer copies in only the
//! files its group reads, so editing app code doesn't invalidate the tools or deps layers.
//! `rootfs`: the OCI result exported and packed into ext4 for microVMs.

use std::path::{Path, PathBuf};
use std::process::Command;

use veneer_exec::{ExecError, Log, Result, run_logged};
use veneer_plan::{BakeInputs, Plan};

/// In-image locations.
pub const PROJECT_DIR: &str = "/opt/veneer/project";
pub const STATE_DIR: &str = "/var/lib/veneer";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Target {
    Oci,
    Rootfs,
    /// The ext4 rootfs converted to qcow2: a root disk for QEMU/KVM, Cloud Hypervisor, or
    /// libvirt direct-kernel boot.
    Qcow2,
    /// A Firecracker bundle directory: `rootfs.ext4` (with `/sbin/veneer-init`), the given
    /// kernel as `vmlinux`, and `vm-config.json` for `firecracker --config-file`.
    Firecracker,
    /// A bootable VM disk (kernel + bootloader, via d2vm) whose boot runs the workspace
    /// phase. Format from the output extension: raw, qcow2, vmdk, vhd, vdi.
    Disk,
    /// `Disk` (raw), uploaded to S3, imported as an EBS snapshot (EC2 VM Import), and
    /// registered as an AMI.
    Ami,
}

#[derive(Debug, Clone)]
pub struct BakeOptions {
    pub target: Target,
    pub tag: String,
    pub push: bool,
    pub platform: Option<String>,
    /// A Linux veneer binary for the image's platform.
    pub veneer_bin: PathBuf,
    /// Output path for `rootfs`.
    pub output: Option<PathBuf>,
    /// Keep the generated build context here (for inspection/debugging).
    pub context_dir: Option<PathBuf>,
    /// Guest kernel (uncompressed vmlinux) for `firecracker`.
    pub kernel: Option<PathBuf>,
    /// AMI publishing.
    pub ami: Option<AmiOptions>,
    /// In-image spec path, used by the microVM init shim.
    pub spec_in_image: String,
}

/// PID 1 inside a microVM: mount the kernel filesystems, then hand over to `veneer entrypoint`
/// (workspace phase, then the command from `veneer.cmd=` on the kernel command line or a shell).
pub fn init_script(spec_in_image: &str) -> String {
    format!(
        r#"#!/bin/sh
# Generated by `veneer bake --target firecracker`. PID 1 of the microVM.
mount -t proc proc /proc 2>/dev/null
mount -t sysfs sysfs /sys 2>/dev/null
mount -t devtmpfs devtmpfs /dev 2>/dev/null
mkdir -p /dev/pts /run /tmp && mount -t devpts devpts /dev/pts 2>/dev/null
hostname veneer 2>/dev/null
export PATH=/usr/local/sbin:/usr/local/bin:/usr/sbin:/usr/bin:/sbin:/bin HOME=/root
export VENEER_STATE_DIR={STATE_DIR}
# Workspace phase (build phase is baked), then a marker `veneer vm snapshot` waits for.
veneer apply {spec_in_image} --phase workspace </dev/null >/dev/console 2>&1 \
  && echo "{READY_MARKER}" >/dev/console
cmd=$(sed -n 's/.*veneer\.cmd=\([^ ]*\).*/\1/p' /proc/cmdline | sed 's/%20/ /g')
exec veneer exec {spec_in_image} -- ${{cmd:-/bin/sh}}
"#
    )
}

#[derive(Debug, Clone, Default)]
pub struct AmiOptions {
    /// S3 bucket for the disk upload (VM Import reads from S3).
    pub bucket: Option<String>,
    pub name: String,
    pub region: Option<String>,
    /// Register this existing EBS snapshot instead of uploading (e.g. made with coldsnap).
    pub snapshot_id: Option<String>,
}

/// Boot services that run the workspace phase when a VM disk boots (systemd and OpenRC).
pub fn boot_service_layer(tag: &str, spec_in_image: &str) -> String {
    format!(
        r#"FROM {tag}
RUN mkdir -p /etc/systemd/system/multi-user.target.wants /etc/init.d /etc/runlevels/default \
 && printf '[Unit]\nDescription=veneer workspace phase\nAfter=network-online.target\nWants=network-online.target\n\n[Service]\nType=oneshot\nEnvironment=VENEER_STATE_DIR={STATE_DIR}\nExecStart=/usr/local/bin/veneer apply {spec_in_image} --phase workspace\nStandardOutput=journal+console\nRemainAfterExit=yes\n\n[Install]\nWantedBy=multi-user.target\n' > /etc/systemd/system/veneer-workspace.service \
 && ln -sf ../veneer-workspace.service /etc/systemd/system/multi-user.target.wants/veneer-workspace.service \
 && printf '#!/sbin/openrc-run\ndescription="veneer workspace phase"\ndepend() {{ after net; }}\nstart() {{ ebegin "veneer workspace"; VENEER_STATE_DIR={STATE_DIR} /usr/local/bin/veneer apply {spec_in_image} --phase workspace >/dev/console 2>&1; eend $?; }}\n' > /etc/init.d/veneer-workspace \
 && chmod +x /etc/init.d/veneer-workspace \
 && ln -sf /etc/init.d/veneer-workspace /etc/runlevels/default/veneer-workspace
"#
    )
}

/// Printed on the serial console once the workspace phase has finished inside the VM.
pub const READY_MARKER: &str = "veneer: workspace ready";

/// Firecracker machine configuration for the bundle (paths relative to the bundle dir).
pub fn firecracker_config() -> String {
    r#"{
  "boot-source": {
    "kernel_image_path": "vmlinux",
    "boot_args": "console=ttyS0 reboot=k panic=1 pci=off init=/sbin/veneer-init"
  },
  "drives": [
    { "drive_id": "rootfs", "path_on_host": "rootfs.ext4", "is_root_device": true, "is_read_only": false }
  ],
  "machine-config": { "vcpu_count": 2, "mem_size_mib": 1024 }
}
"#
        .to_string()
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Baked {
    pub image: String,
    pub id: Option<String>,
    pub rootfs: Option<PathBuf>,
    pub containerfile: String,
    /// Registered AMI id (`--target ami`).
    pub ami: Option<String>,
}

const SKIP_DIRS: &[&str] = &[".git", "target", "node_modules", ".venv", ".veneer-state"];

fn copy_tree(from: &Path, to: &Path) -> std::io::Result<()> {
    std::fs::create_dir_all(to)?;
    for entry in std::fs::read_dir(from)? {
        let entry = entry?;
        let name = entry.file_name();
        if SKIP_DIRS.iter().any(|s| name == *s) {
            continue;
        }
        let ty = entry.file_type()?;
        let dest = to.join(&name);
        if ty.is_dir() {
            copy_tree(&entry.path(), &dest)?;
        } else if ty.is_symlink() {
            let target = std::fs::read_link(entry.path())?;
            let _ = std::os::unix::fs::symlink(target, dest);
        } else {
            std::fs::copy(entry.path(), dest)?;
        }
    }
    Ok(())
}

fn stage(project: &Path, files: &[PathBuf], dir: &Path) -> Result<()> {
    for f in files {
        let rel = f.strip_prefix(project).map_err(|_| {
            ExecError::failed(format!(
                "bake needs every input inside the project root ({}); {} is outside it",
                project.display(),
                f.display()
            ))
        })?;
        let dest = dir.join(rel);
        std::fs::create_dir_all(dest.parent().unwrap())
            .map_err(|e| ExecError::failed(e.to_string()))?;
        std::fs::copy(f, &dest)
            .map_err(|e| ExecError::failed(format!("cannot copy {}: {e}", f.display())))?;
    }
    Ok(())
}

fn q(s: &str) -> String {
    serde_like_json(s)
}

fn serde_like_json(s: &str) -> String {
    let mut out = String::from("\"");
    for c in s.chars() {
        match c {
            '"' => out.push_str("\\\""),
            '\\' => out.push_str("\\\\"),
            c => out.push(c),
        }
    }
    out.push('"');
    out
}

/// Everything one bake needs besides the build context directory.
pub struct BakeJob<'a> {
    pub base: &'a str,
    pub plan: &'a Plan,
    pub entry: &'a Path,
    pub documents: &'a [PathBuf],
    pub inputs: &'a BakeInputs,
    pub veneer_bin: &'a Path,
    /// Overlay files (absolute, inside the project) passed to every in-image invocation.
    pub overlays: &'a [PathBuf],
    pub sets: &'a [(String, String)],
}

/// Generates the Containerfile and stages the build context in `ctx`.
pub fn prepare(job: &BakeJob<'_>, ctx: &Path) -> Result<String> {
    let BakeJob {
        base,
        plan,
        entry,
        documents,
        inputs,
        veneer_bin,
        overlays,
        sets,
    } = *job;
    let project = &plan.project_root;
    let entry_rel = entry
        .strip_prefix(project)
        .map_err(|_| ExecError::failed("the spec must live inside the project root"))?
        .display()
        .to_string();
    std::fs::create_dir_all(ctx).map_err(|e| ExecError::failed(e.to_string()))?;
    std::fs::copy(veneer_bin, ctx.join("veneer")).map_err(|e| {
        ExecError::failed(format!(
            "cannot copy veneer binary {}: {e}",
            veneer_bin.display()
        ))
    })?;

    let groups: Vec<&str> = {
        let mut g: Vec<&str> = Vec::new();
        for s in &plan.steps {
            if !g.contains(&s.group.as_str()) {
                g.push(&s.group);
            }
        }
        g
    };
    let has = |g: &str| groups.contains(&g);
    // `--overlay`/`--set` must reach every in-image invocation, or the image would be built
    // from a different spec than the one the user baked.
    let mut extra = String::new();
    for o in overlays {
        let rel = o.strip_prefix(project).map_err(|_| {
            ExecError::failed(format!(
                "overlay {} must be inside the project root to bake",
                o.display()
            ))
        })?;
        extra.push_str(&format!(
            ", \"--overlay\", {}",
            q(&format!("{PROJECT_DIR}/{}", rel.display()))
        ));
    }
    for (k, v) in sets {
        extra.push_str(&format!(", \"--set\", {}", q(&format!("{k}={v}"))));
    }
    let run = |group: &str| {
        format!(
            "RUN [\"veneer\", \"apply\", \"--phase\", \"build\", \"--only\", {}{extra}, {}]\n",
            q(group),
            q(&entry_rel)
        )
    };

    let mut cf = String::new();
    cf.push_str("# syntax=docker/dockerfile:1\n# Generated by `veneer bake`. Do not edit.\n");
    cf.push_str(&format!("FROM {base}\n"));
    cf.push_str(&format!("ENV VENEER_STATE_DIR={STATE_DIR}\n"));
    cf.push_str("COPY veneer /usr/local/bin/veneer\n");

    // Layer: spec documents + packages/tools imports.
    let mut early: Vec<PathBuf> = documents
        .iter()
        .filter(|d| d.starts_with(project))
        .cloned()
        .collect();
    early.extend(inputs.early.iter().cloned());
    early.extend(overlays.iter().cloned());
    stage(project, &early, &ctx.join("ctx-spec"))?;
    cf.push_str(&format!(
        "COPY ctx-spec/ {PROJECT_DIR}/\nWORKDIR {PROJECT_DIR}\n"
    ));
    for g in ["packages", "nix", "tools"] {
        if has(g) {
            cf.push_str(&run(g));
        }
    }
    // One layer per dependency lockfile.
    for (i, (group, manifest, lock)) in inputs.deps.iter().enumerate() {
        let mut files = vec![manifest.clone()];
        files.extend(lock.iter().cloned());
        let dir = format!("ctx-deps-{i}");
        stage(project, &files, &ctx.join(&dir))?;
        cf.push_str(&format!("COPY {dir}/ {PROJECT_DIR}/\n"));
        cf.push_str(&run(group));
    }
    // Everything else.
    copy_tree(project, &ctx.join("ctx-project"))
        .map_err(|e| ExecError::failed(format!("cannot stage project: {e}")))?;
    cf.push_str(&format!("COPY ctx-project/ {PROJECT_DIR}/\n"));
    if has("images") {
        cf.push_str(&run("images"));
    }
    // Final pass: build hooks, and re-verifies every earlier group (all skip when intact).
    cf.push_str(&format!(
        "RUN [\"veneer\", \"apply\", \"--phase\", \"build\"{extra}, {}]\n",
        q(&entry_rel)
    ));
    cf.push_str(&format!(
        "ENTRYPOINT [\"veneer\", \"entrypoint\"{extra}, {}, \"--\"]\nCMD [\"sh\"]\n",
        q(&format!("{PROJECT_DIR}/{entry_rel}"))
    ));
    std::fs::write(ctx.join("Containerfile"), &cf).map_err(|e| ExecError::failed(e.to_string()))?;
    Ok(cf)
}

fn has_cmd(program: &str, args: &[&str]) -> bool {
    Command::new(program)
        .args(args)
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .status()
        .is_ok_and(|s| s.success())
}

/// Builds the staged context with docker buildx, or rootless buildah.
pub fn build(ctx: &Path, opts: &BakeOptions, log: &mut Log) -> Result<Baked> {
    let containerfile = std::fs::read_to_string(ctx.join("Containerfile")).unwrap_or_default();
    if has_cmd("docker", &["buildx", "version"]) {
        let mut c = Command::new("docker");
        c.args(["buildx", "build", "-f"])
            .arg(ctx.join("Containerfile"))
            .args(["-t", &opts.tag]);
        if let Some(p) = &opts.platform {
            c.args(["--platform", p]);
        }
        c.arg(if opts.push { "--push" } else { "--load" });
        c.arg(ctx);
        run_logged(&mut c, log)?;
    } else if has_cmd("buildah", &["--version"]) {
        let mut c = Command::new("buildah");
        c.args(["bud", "-f"])
            .arg(ctx.join("Containerfile"))
            .args(["-t", &opts.tag]);
        if let Some(p) = &opts.platform {
            c.args(["--platform", p]);
        }
        c.arg(ctx);
        run_logged(&mut c, log)?;
        if opts.push {
            run_logged(Command::new("buildah").args(["push", &opts.tag]), log)?;
        }
    } else {
        return Err(ExecError::failed("bake needs `docker buildx` or `buildah`"));
    }
    let id = Command::new("docker")
        .args(["image", "inspect", "--format", "{{.Id}}", &opts.tag])
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string());
    let mut baked = Baked {
        image: opts.tag.clone(),
        id,
        rootfs: None,
        containerfile,
        ami: None,
    };
    match opts.target {
        Target::Oci => {}
        Target::Rootfs => {
            let ext4 = rootfs(ctx, opts, log)?;
            let out = opts
                .output
                .clone()
                .unwrap_or_else(|| PathBuf::from("rootfs.ext4"));
            std::fs::copy(&ext4, &out).map_err(|e| ExecError::failed(e.to_string()))?;
            baked.rootfs = Some(out);
        }
        Target::Firecracker => {
            let kernel = opts.kernel.clone().ok_or_else(|| {
                ExecError::failed("--target firecracker needs --kernel <vmlinux>")
            })?;
            std::fs::write(ctx.join("veneer-init"), init_script(&opts.spec_in_image))
                .map_err(|e| ExecError::failed(e.to_string()))?;
            rootfs(ctx, opts, log)?;
            let out = opts
                .output
                .clone()
                .unwrap_or_else(|| PathBuf::from("firecracker"));
            std::fs::create_dir_all(&out).map_err(|e| ExecError::failed(e.to_string()))?;
            std::fs::copy(ctx.join("rootfs.ext4"), out.join("rootfs.ext4"))
                .map_err(|e| ExecError::failed(e.to_string()))?;
            std::fs::copy(&kernel, out.join("vmlinux")).map_err(|e| {
                ExecError::failed(format!("cannot copy kernel {}: {e}", kernel.display()))
            })?;
            std::fs::write(out.join("vm-config.json"), firecracker_config())
                .map_err(|e| ExecError::failed(e.to_string()))?;
            baked.rootfs = Some(out);
        }
        Target::Disk | Target::Ami => {
            let out = match opts.target {
                Target::Ami => ctx.join("disk.raw"),
                _ => opts
                    .output
                    .clone()
                    .unwrap_or_else(|| PathBuf::from("disk.qcow2")),
            };
            disk(ctx, opts, &out, log)?;
            if opts.target == Target::Ami {
                baked.ami = Some(publish_ami(&out, opts, log)?);
            }
            baked.rootfs = Some(out);
        }
        Target::Qcow2 => {
            rootfs(ctx, opts, log)?;
            run_logged(
                Command::new("docker")
                    .args(["run", "--rm", "-v"])
                    .arg(format!("{}:/w", ctx.display()))
                    .args([
                        "alpine:3.20",
                        "sh",
                        "-c",
                        "set -e; apk add --no-cache qemu-img >/dev/null; qemu-img convert -f raw -O qcow2 /w/rootfs.ext4 /w/disk.qcow2",
                    ]),
                log,
            )?;
            let out = opts
                .output
                .clone()
                .unwrap_or_else(|| PathBuf::from("disk.qcow2"));
            std::fs::copy(ctx.join("disk.qcow2"), &out)
                .map_err(|e| ExecError::failed(e.to_string()))?;
            baked.rootfs = Some(out);
        }
    }
    Ok(baked)
}

/// Exports the built image and packs it into `<ctx>/rootfs.ext4` with a helper container.
fn rootfs(ctx: &Path, opts: &BakeOptions, log: &mut Log) -> Result<PathBuf> {
    let tar = ctx.join("rootfs.tar");
    let cid = Command::new("docker")
        .args(["create", &opts.tag])
        .output()
        .map_err(|e| ExecError::failed(e.to_string()))?;
    if !cid.status.success() {
        return Err(ExecError::failed(format!(
            "docker create {} failed",
            opts.tag
        )));
    }
    let cid = String::from_utf8_lossy(&cid.stdout).trim().to_string();
    let exported = run_logged(
        Command::new("docker")
            .args(["export", "-o"])
            .arg(&tar)
            .arg(&cid),
        log,
    );
    let _ = Command::new("docker").args(["rm", &cid]).output();
    exported?;
    let size_mb = std::fs::metadata(&tar)
        .map(|m| m.len() / (1024 * 1024))
        .unwrap_or(256)
        * 3
        / 2
        + 128;
    let script = format!(
        "set -e; apk add --no-cache e2fsprogs >/dev/null; mkdir /r; tar -xf /w/rootfs.tar -C /r; \
         if [ -f /w/veneer-init ]; then install -m 0755 /w/veneer-init /r/sbin/veneer-init; fi; \
         mkfs.ext4 -q -F -d /r /w/rootfs.ext4 {size_mb}M"
    );
    run_logged(
        Command::new("docker")
            .args(["run", "--rm", "-v"])
            .arg(format!("{}:/w", ctx.display()))
            .args(["alpine:3.20", "sh", "-c", &script]),
        log,
    )?;
    Ok(ctx.join("rootfs.ext4"))
}

/// Builds a bootable disk from the image plus the boot-service layer, with d2vm.
fn disk(ctx: &Path, opts: &BakeOptions, out: &Path, log: &mut Log) -> Result<()> {
    let boot_tag = format!(
        "{}-boot:latest",
        opts.tag.split(':').next().unwrap_or(&opts.tag)
    );
    let dir = ctx.join("boot-layer");
    std::fs::create_dir_all(&dir).map_err(|e| ExecError::failed(e.to_string()))?;
    std::fs::write(
        dir.join("Containerfile"),
        boot_service_layer(&opts.tag, &opts.spec_in_image),
    )
    .map_err(|e| ExecError::failed(e.to_string()))?;
    run_logged(
        Command::new("docker")
            .args(["build", "-q", "-t", &boot_tag, "-f"])
            .arg(dir.join("Containerfile"))
            .arg(&dir),
        log,
    )?;
    let platform = opts.platform.clone().unwrap_or_else(|| {
        format!(
            "linux/{}",
            if std::env::consts::ARCH == "aarch64" {
                "arm64"
            } else {
                "amd64"
            }
        )
    });
    let name = out
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("disk.qcow2")
        .to_string();
    let work = ctx.join("disk-out");
    std::fs::create_dir_all(&work).map_err(|e| ExecError::failed(e.to_string()))?;
    run_logged(
        Command::new("docker")
            .args([
                "run",
                "--rm",
                "--privileged",
                "-v",
                "/var/run/docker.sock:/var/run/docker.sock",
                "-v",
            ])
            .arg(format!("{}:/d2vm", work.display()))
            .args([
                "-w",
                "/d2vm",
                "linkacloud/d2vm:latest",
                "convert",
                &boot_tag,
                "-o",
                &name,
                "--size",
                "4G",
            ])
            .args(["--platform", &platform])
            // arm64 QEMU/KVM consoles are PL011 (ttyAMA0); EC2 and amd64 use ttyS0. The last
            // `console=` becomes /dev/console, where the boot service reports progress.
            .args([
                "--append-to-cmdline",
                if platform.ends_with("arm64") {
                    "console=ttyS0 console=ttyAMA0"
                } else {
                    "console=ttyS0"
                },
            ]),
        log,
    )?;
    std::fs::rename(work.join(&name), out)
        .or_else(|_| std::fs::copy(work.join(&name), out).map(|_| ()))
        .map_err(|e| ExecError::failed(format!("cannot place disk at {}: {e}", out.display())))
}

/// `aws` CLI: the host's, or the official amazon/aws-cli image with credentials passed through.
fn aws(args: &[&str], mount: Option<&Path>, log: &mut Log) -> Result<String> {
    let host_aws = std::env::var_os("PATH").and_then(|p| {
        std::env::split_paths(&p)
            .map(|d| d.join("aws"))
            .find(|p| p.is_file())
    });
    let mut c = match host_aws {
        Some(bin) => {
            let mut c = Command::new(bin);
            c.args(args);
            c
        }
        None => {
            let mut c = Command::new("docker");
            c.args(["run", "--rm", "--network", "host"]);
            for k in [
                "AWS_ACCESS_KEY_ID",
                "AWS_SECRET_ACCESS_KEY",
                "AWS_SESSION_TOKEN",
                "AWS_REGION",
                "AWS_DEFAULT_REGION",
                "AWS_PROFILE",
                "AWS_ENDPOINT_URL",
            ] {
                if std::env::var_os(k).is_some() {
                    c.args(["-e", k]);
                }
            }
            if let Some(home) = std::env::var_os("HOME") {
                let aws_dir = Path::new(&home).join(".aws");
                if aws_dir.is_dir() {
                    c.arg("-v")
                        .arg(format!("{}:/root/.aws:ro", aws_dir.display()));
                }
            }
            if let Some(m) = mount {
                c.arg("-v")
                    .arg(format!("{}:{}:ro", m.display(), m.display()));
            }
            c.arg("amazon/aws-cli").args(args);
            c
        }
    };
    log.line(&format!("$ aws {}", args.join(" ")));
    let out = c
        .output()
        .map_err(|e| ExecError::failed(format!("cannot run aws: {e}")))?;
    log.line(&String::from_utf8_lossy(&out.stdout));
    log.line(&String::from_utf8_lossy(&out.stderr));
    if !out.status.success() {
        return Err(ExecError::failed(format!(
            "aws {} failed: {}",
            args.first().copied().unwrap_or_default(),
            String::from_utf8_lossy(&out.stderr).trim()
        )));
    }
    Ok(String::from_utf8_lossy(&out.stdout).trim().to_string())
}

/// Uploads `disk` and registers an AMI. Returns the AMI id.
fn publish_ami(disk: &Path, opts: &BakeOptions, log: &mut Log) -> Result<String> {
    let ami = opts.ami.clone().unwrap_or_default();
    let region: Vec<&str> = ami
        .region
        .as_deref()
        .map(|r| vec!["--region", r])
        .unwrap_or_default();
    let snapshot = match &ami.snapshot_id {
        Some(s) => s.clone(),
        None => {
            let bucket = ami.bucket.as_deref().ok_or_else(|| {
                ExecError::failed("--target ami needs --s3-bucket (or --snapshot-id)")
            })?;
            let key = format!("veneer/{}-{}.raw", ami.name, std::process::id());
            let dir = disk.parent().unwrap_or(Path::new("."));
            let disk_s = disk.display().to_string();
            let dest = format!("s3://{bucket}/{key}");
            let mut cp = vec!["s3", "cp", disk_s.as_str(), dest.as_str()];
            cp.extend(region.iter().copied());
            aws(&cp, Some(dir), log)?;
            let container = format!("Format=raw,UserBucket={{S3Bucket={bucket},S3Key={key}}}");
            let mut imp = vec![
                "ec2",
                "import-snapshot",
                "--disk-container",
                container.as_str(),
                "--query",
                "ImportTaskId",
                "--output",
                "text",
            ];
            imp.extend(region.iter().copied());
            let task = aws(&imp, None, log)?;
            loop {
                let mut d = vec![
                    "ec2",
                    "describe-import-snapshot-tasks",
                    "--import-task-ids",
                    task.as_str(),
                    "--query",
                    "ImportSnapshotTasks[0].SnapshotTaskDetail.[Status,SnapshotId,StatusMessage]",
                    "--output",
                    "text",
                ];
                d.extend(region.iter().copied());
                let line = aws(&d, None, log)?;
                let parts: Vec<&str> = line.split_whitespace().collect();
                match parts.first().copied() {
                    Some("completed") => {
                        break parts.get(1).copied().unwrap_or_default().to_string();
                    }
                    Some("deleted") | Some("deleting") => {
                        return Err(ExecError::failed(format!("EC2 import failed: {line}")));
                    }
                    _ => std::thread::sleep(std::time::Duration::from_secs(15)),
                }
            }
        }
    };
    let arch = match opts.platform.as_deref() {
        Some(p) if p.ends_with("amd64") => "x86_64",
        Some(_) => "arm64",
        None if std::env::consts::ARCH == "aarch64" => "arm64",
        None => "x86_64",
    };
    let bdm =
        format!("DeviceName=/dev/xvda,Ebs={{SnapshotId={snapshot},DeleteOnTermination=true}}");
    let mut reg = vec![
        "ec2",
        "register-image",
        "--name",
        ami.name.as_str(),
        "--architecture",
        arch,
        "--root-device-name",
        "/dev/xvda",
        "--block-device-mappings",
        bdm.as_str(),
        "--virtualization-type",
        "hvm",
        "--boot-mode",
        "uefi",
        "--ena-support",
        "--query",
        "ImageId",
        "--output",
        "text",
    ];
    reg.extend(region.iter().copied());
    aws(&reg, None, log)
}
